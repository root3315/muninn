/** The headset's string if it has one, the site's otherwise. */
export function tv(key, vars) {
  const own = STRINGS[getLanguage()]?.[key] ?? STRINGS.en[key];
  if (own === undefined) return t(key, vars);
  let s = own;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

